'use strict';
// Offline development tool. Source banks stay editable; browser receives compact immutable JSON.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const repo=path.resolve(__dirname,'..'),js=path.join(repo,'assets/js'),dir=path.join(repo,'assets/promo-banks');
const hash=s=>{let h=2166136261;for(let i=0;i<s.length;i++){h^=s.charCodeAt(i);h=Math.imul(h,16777619);}return (h>>>0).toString(16).padStart(8,'0');};
function build(){
 const root={};
 const names=['promo-dialogue-pilot.js',...fs.readdirSync(js).filter(n=>/^promo-dialogue-bank-.*\.js$/.test(n)).sort()];
 for(const name of ['promo-dialogue.js',...names])vm.runInNewContext(fs.readFileSync(path.join(js,name),'utf8'),{window:root});
 const packs=root.OfficePromoDialogue.combine(...Object.entries(root).filter(([k])=>k==='OfficePromoPilot'||/^OfficePromoBank[A-Z0-9]+$/.test(k)).map(([,v])=>v));
 // Academy rookies without an authored bank get a generated one (deterministic, from their identity).
 const authoredOwners=new Set(packs.map(p=>p.owner));
 const generated=require('./build-rookie-banks.cjs').generate(authoredOwners);
 packs.push(...generated.packs);
 root.OfficePromoDialogue.catalogue(packs);
 const claimKeys={};
 for(const pack of generated.packs)for(const l of pack.lines)if(generated.claims[l.id])claimKeys['bank:'+l.id+':'+hash(l.text)]=generated.claims[l.id];
 const claimsScript="/* Generated by scripts/build-promo-banks.cjs; do not edit. */\n(function(root){'use strict';root.OfficePromoRookieClaims=Object.freeze("+JSON.stringify(Object.fromEntries(Object.entries(claimKeys).sort()),null,1)+");})(typeof window!=='undefined'?window:globalThis);\n";
 const manifest={},assets=new Map();
 for(const pack of packs.sort((a,b)=>a.owner.localeCompare(b.owner))){
  if(pack.role!=='wrestler')throw Error('Extend asset schema before packing non-wrestler roles');
  const rows=pack.lines.map(({id,stage,action,side,category,text,when={}})=>{
   if(!id.startsWith(pack.owner+'.'))throw Error('Invalid owner prefix: '+id);
   // Strength is a plural noun phrase, even for unknown wrestling styles.
   if(/\{strength\}\s+(?:is|was|has|does)\b/i.test(text)||/\b(?:a|an|this|that)\s+\{strength\}/i.test(text))throw Error('Strength placeholder agreement: '+id);
   const {variants,hasMouthpiece,...extra}=when;
   if(hasMouthpiece!==false)extra.hasMouthpiece=hasMouthpiece??false;
   const row=[id.slice(pack.owner.length+1),stage,action,side,category,text,variants||null];
   if(Object.keys(extra).length)row.push(extra);
   return row;
  });
  const raw=JSON.stringify({v:1,owner:pack.owner,rows}),rev=hash(raw);
  manifest[pack.owner]=rev;assets.set(pack.owner+'.'+rev+'.json',raw);
 }
 const script="/* Generated by scripts/build-promo-banks.cjs; do not edit. */\n(function(root){'use strict';root.OfficePromoBankManifest=Object.freeze("+JSON.stringify(manifest)+");})(typeof window!=='undefined'?window:globalThis);\n";
 return {assets,script,packs,names,claimsScript,generatedOwners:generated.packs.map(p=>p.owner)};
}
// Only generated, revisioned bank files are ours to delete; anything else in the folder is left alone.
const generated=/^[a-z0-9-]+\.[0-9a-f]{8}\.json$/;
function staleFiles(built){
 if(!fs.existsSync(dir))return [];
 return fs.readdirSync(dir).filter(n=>generated.test(n)&&!built.assets.has(n));
}
function check(){
 const built=build(),m=path.join(js,'promo-bank-manifest.js');
 if(fs.readFileSync(m,'utf8').replace(/\r\n/g,'\n')!==built.script)throw Error('Stale promo bank manifest; run node scripts/build-promo-banks.cjs');
 for(const [name,raw] of built.assets)if(fs.readFileSync(path.join(dir,name),'utf8')!==raw)throw Error('Stale bank: '+name);
 if(fs.readFileSync(path.join(js,'promo-rookie-claims.js'),'utf8')!==built.claimsScript)throw Error('Stale rookie claims; run node scripts/build-promo-banks.cjs');
 const stale=staleFiles(built);
 if(stale.length)throw Error('Unreferenced promo bank revisions (run node scripts/build-promo-banks.cjs): '+stale.join(', '));
 return built;
}
if(require.main===module){
 if(process.argv.includes('--check'))check();
 else {
  const b=build();fs.mkdirSync(dir,{recursive:true});
  for(const name of staleFiles(b))fs.rmSync(path.join(dir,name));
  for(const [name,raw] of b.assets)fs.writeFileSync(path.join(dir,name),raw);
  fs.writeFileSync(path.join(js,'promo-bank-manifest.js'),b.script);
  fs.writeFileSync(path.join(js,'promo-rookie-claims.js'),b.claimsScript);
 }
}
module.exports={build,check};

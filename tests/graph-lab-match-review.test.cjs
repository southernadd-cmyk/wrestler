'use strict';
const assert=require('node:assert/strict');
const fixtures=require('../tools/graph-lab/review-scenarios.js');
const review=require('../tools/graph-lab/match-review.cjs');
assert.equal(fixtures.cases.length,6);
assert.equal(new Set(fixtures.cases.map(x=>x.seed)).size,6);
assert.equal(fixtures.cases.reduce((sum,x)=>sum+x.count,0),600);
assert.equal(fixtures.get('rivalry').rotation,'fixed');
assert.equal(fixtures.get('aerial').plan,'spots');
assert.equal(fixtures.get('nonexistent'),null);
const before=review.capture(3),again=review.capture(3);
assert.equal(before.schema,'office-graph-lab-review-v05');
assert.equal(before.totalBouts,18);
assert.equal(before.registry.reviewed,325);
assert.equal(before.registry.authored,340);
assert.deepEqual(before,again,'identical seeds and roster choices must repeat exactly');
assert.deepEqual(review.failures(before),[],'all six real match scenarios are mechanically valid');
assert.ok(before.scenarios.every(row=>row.uniqueMatchSequences>0));
assert.match(review.markdown(before),/Mechanical validation:\*\* passed/);
console.log('PASS v0.5 Graph Lab: 6 seeded match-review scenarios, replayed deterministically, full engine and validation.');

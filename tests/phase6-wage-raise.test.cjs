assert.ok(s.inbox.some(m=>m.subject.includes('A voluntary wage increase')),'the office records the wage decision');
const before=JSON.stringify(s);assert.match(A.giveRaise('rex').error,/Next review/);
assert.equal(JSON.stringify(s),before,'repeat click cannot create another wage increase');
G.S=JSON.parse(JSON.stringify(s));
assert.equal(G.W('rex').wage,old+40,'new wage survives save hydration');
assert.match(A.raiseAvailable('rex').error,/Next review/,'review cooldown survives save hydration');
assert.match(A.giveRaise('not-on-the-roster').error,/no longer in your stable/);
const ui=fs.readFileSync(path.join(__dirname,'../assets/js/ui.js'),'utf8');
assert.match(ui,/data-raise="\$\{w\.id\}"/);
assert.match(ui,/Confirm permanent raise/);assert.match(ui,/a recurring cost every week/);

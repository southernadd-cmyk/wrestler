'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {engine}=require('./_world.cjs');
const {root}=engine(6026);
const {OfficeGame:G,OfficeAmbitions:A}=root;
G.fresh();const s=G.S;s.cash=99999;assert.equal(G.sign('rex'),null);
const w=G.W('rex'),old=w.wage,oldPayroll=G.wages(),oldCash=s.cash;
const e=A.entry('rex');e.kind='money';e.sat=40;e.wageAt=old;
assert.equal(A.raiseAvailable(w.id).error,null);
const raised=A.giveRaise(w.id);assert.match(raised.text,/£40 weekly raise/);
assert.equal(w.wage,old+40);assert.equal(G.wages(),oldPayroll+40);
assert.equal(s.cash,oldCash,'a raise increases future payroll, not immediate cash');
